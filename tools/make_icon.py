"""Render the DOOM wordmark (assets/doom-logo.svg, a public-domain text logo) into
K15 stock-style UI icons, or into a C header of polygons for the engine's own menus.

  make_icon.py icon <out.png> [--width 62] [--style fill|outline] [--stroke 2.4]
  make_icon.py header <out.h>
  make_icon.py preview <out.png>      # styles side by side on the grid colour, for review

The stock icons are single-colour anti-aliased line art in brown (79,45,8); the UI
recolours the selected state itself. At icon size the filled wordmark reads far better than
an outline (the letter counters are only a few pixels wide), so `fill` is the default.
"""
import argparse
import os
import re

from PIL import Image, ImageChops, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
SVG = os.path.join(HERE, "..", "assets", "doom-logo.svg")
BROWN = (79, 45, 8)
SS = 8  # supersampling factor


def load_subpaths(svg=SVG):
    """Parse the logo's single <path d="..."> (M/L/H/V/Z, absolute + relative).
    Returns the closed sub-paths shifted to a (0,0) origin, plus the logo width/height."""
    d = re.search(r'\sd="([^"]+)"', open(svg, encoding="utf-8").read()).group(1)
    toks = re.findall(r"[MmLlHhVvZz]|-?(?:\d+\.?\d*|\.\d+)(?:e-?\d+)?", d)
    subs, cur, cmd = [], [], None
    x = y = sx = sy = 0.0
    i = 0
    while i < len(toks):
        t = toks[i]
        if t.isalpha():
            cmd = t
            i += 1
            if cmd in "Zz":
                if cur:
                    subs.append(cur)
                cur, x, y = [], sx, sy
            continue
        if cmd in "Mm":
            if cur:
                subs.append(cur)
            dx, dy = float(toks[i]), float(toks[i + 1])
            i += 2
            x, y = (x + dx, y + dy) if cmd == "m" else (dx, dy)
            sx, sy, cur = x, y, [(x, y)]
            cmd = "l" if cmd == "m" else "L"  # implicit lineto after a moveto
        elif cmd in "Ll":
            dx, dy = float(toks[i]), float(toks[i + 1])
            i += 2
            x, y = (x + dx, y + dy) if cmd == "l" else (dx, dy)
            cur.append((x, y))
        elif cmd in "Hh":
            v = float(toks[i])
            i += 1
            x = x + v if cmd == "h" else v
            cur.append((x, y))
        elif cmd in "Vv":
            v = float(toks[i])
            i += 1
            y = y + v if cmd == "v" else v
            cur.append((x, y))
        else:
            raise ValueError("unsupported path command " + str(cmd))
    if cur:
        subs.append(cur)
    xs = [p[0] for s in subs for p in s]
    ys = [p[1] for s in subs for p in s]
    x0, y0 = min(xs), min(ys)
    subs = [[(px - x0, py - y0) for px, py in s] for s in subs]
    return subs, max(xs) - x0, max(ys) - y0


def render(width, style="fill", stroke=2.4, colour=BROWN):
    subs, lw, lh = load_subpaths()
    pad = stroke / 2 + 0.5 if style == "outline" else 0.5
    scale = (width - 2 * pad) / lw
    height = int(round(lh * scale + 2 * pad))
    W, H = width * SS, height * SS
    mask = Image.new("1", (W, H), 0)
    lines = Image.new("L", (W, H), 0)
    for s in subs:
        pts = [((px * scale + pad) * SS, (py * scale + pad) * SS) for px, py in s]
        if style == "fill":
            m = Image.new("1", (W, H), 0)
            ImageDraw.Draw(m).polygon(pts, fill=1)
            mask = ImageChops.logical_xor(mask, m)  # even-odd: inner D/O counters are holes
        else:
            ImageDraw.Draw(lines).line(pts + pts[:2], fill=255,
                                       width=max(1, int(round(stroke * SS))), joint="curve")
    full = mask.convert("L") if style == "fill" else lines
    alpha = full.resize((width, height), Image.BOX)
    img = Image.new("RGBA", (width, height), colour + (0,))
    img.putalpha(alpha)
    return img


def header(out):
    subs, lw, lh = load_subpaths()
    lines = [
        "// Generated by doom-fw/tools/make_icon.py from assets/doom-logo.svg (public-domain",
        "// text logo). The DOOM wordmark as closed polygons, even-odd fill, logo units.",
        "#pragma once",
        f"#define K15_LOGO_W {int(round(lw))}",
        f"#define K15_LOGO_H {int(round(lh))}",
        f"#define K15_LOGO_NPOLY {len(subs)}",
        "static const unsigned char k15_logo_len[K15_LOGO_NPOLY] = {" +
        ", ".join(str(len(s)) for s in subs) + "};",
        "static const short k15_logo_pts[][2] = {",
    ]
    for s in subs:
        lines.append("    " + " ".join(f"{{{int(round(x))}, {int(round(y))}}}," for x, y in s))
    lines.append("};")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(out, len(subs), "polygons,", sum(map(len, subs)), "points")


def preview(out):
    variants = [("outline", 2.4), ("outline", 3.0), ("fill", 0)]
    canvas = Image.new("RGBA", (40 + 130 * len(variants), 130), (220, 128, 40, 255))
    for col, (style, stroke) in enumerate(variants):
        for row, colour in enumerate((BROWN, (255, 255, 255))):
            ic = render(58, style, stroke or 2.4, colour)
            canvas.alpha_composite(ic, (20 + col * 130, 15 + row * 60))
    canvas.resize((canvas.width * 3, canvas.height * 3), Image.NEAREST).save(out)
    print(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["icon", "header", "preview"])
    ap.add_argument("out")
    ap.add_argument("--width", type=int, default=62)
    ap.add_argument("--style", choices=["fill", "outline"], default="fill")
    ap.add_argument("--stroke", type=float, default=2.4)
    a = ap.parse_args()
    if a.mode == "icon":
        img = render(a.width, a.style, a.stroke)
        img.save(a.out)
        print(a.out, img.size)
    elif a.mode == "header":
        header(a.out)
    else:
        preview(a.out)


if __name__ == "__main__":
    main()
